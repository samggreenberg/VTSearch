"""Figures for the scale study (#3156), from the same cells the tables read.

Four figures, each answering a question prose cannot:

1. **cost over votes spent, one line per band** -- what a user gets after N
   clicks, which is the axis they actually spend.
2. **the same, one line per run** -- because a mean hides that some runs never
   leave the floor, and that spread is usually the real finding.
3. **cost by band, per encoder** -- the study's own axis, with the encoders side
   by side so a band effect that survives all three is visible as such.
4. **paired small-minus-large per class** -- which classes carry the effect,
   since a pooled mean can be produced by two classes out of twelve.

Generated by committed code so the numbers in the report and the numbers in the
pictures cannot drift apart.
"""

from __future__ import annotations

import argparse
import csv
import glob
import math
import os
from collections import defaultdict
from pathlib import Path

# One wrapped-panel-grid helper, not two: both figure scripts face the same
# problem (a row of panels that grows with the arm count) and a second copy is
# a second place for the wrap rule to be different.
from figures_overview import panel_grid

BANDS = ("small", "medium", "large")
COLORS = {"small": "#c2410c", "medium": "#0f766e", "large": "#3730a3"}


def band_of(c: str) -> str:
    return c.rsplit("@", 1)[1] if "@" in c else ""


def class_of(c: str) -> str:
    return c.rsplit("@", 1)[0]


def mean_se(xs):
    n = len(xs)
    if not n:
        return float("nan"), float("nan")
    m = sum(xs) / n
    if n < 2:
        return m, 0.0
    var = sum((x - m) ** 2 for x in xs) / (n - 1)
    return m, math.sqrt(var / n)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--exp", default=f"/expscratch/{os.environ.get('USER', 'sgreenberg')}/scale-3156")
    ap.add_argument("--out", default="")
    args = ap.parse_args()

    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    cells = Path(args.exp) / "results" / "cells"
    out = Path(args.out or (Path(args.exp) / "figures"))
    out.mkdir(parents=True, exist_ok=True)

    rows = []
    for f in sorted(glob.glob(str(cells / "task_*.csv"))):
        if "__" in Path(f).name:
            continue
        with open(f, newline="") as fh:
            rows.extend(list(csv.DictReader(fh)))
    print(f"{len(rows)} rows")

    # (arm, band) -> {t: [costs]} and per-run trajectories
    traj = defaultdict(lambda: defaultdict(list))
    runs = defaultdict(list)
    endpoint = defaultdict(list)
    per_class = defaultdict(dict)
    for r in rows:
        try:
            t, cost = int(r["t"]), float(r["cost"])
        except (KeyError, ValueError, TypeError):
            continue
        b = band_of(r["category"])
        if b not in BANDS:
            continue
        arm = f"{r.get('embedder', '')}/{r.get('style', '')}".strip("/")
        traj[(arm, b)][t].append(cost)
        runs[(arm, b, r["category"], r["seed"])].append((t, cost))
        endpoint[(arm, b)].append(cost) if t >= 150 else None
        if t >= 150:
            per_class[(arm, class_of(r["category"]), r["seed"])][b] = cost

    arms = sorted({a for a, _ in traj})

    # 1 + 2: trajectories, averaged and per-run
    for per_run in (False, True):
        # Wrapped at three: five arms in one row is a 26-inch figure, and a
        # report renders it scaled to the column width (see `panel_grid`).
        fig, axes, leftmost = panel_grid(len(arms), 5.2, 4.2)
        for ax, arm in zip(axes, arms):
            for b in BANDS:
                if per_run:
                    for (a, bb, _cat, _seed), pts in runs.items():
                        if a != arm or bb != b:
                            continue
                        pts = sorted(pts)
                        ax.plot([p[0] for p in pts], [p[1] for p in pts], color=COLORS[b], alpha=0.10, linewidth=0.7)
                ts = sorted(traj[(arm, b)])
                ms = [mean_se(traj[(arm, b)][t])[0] for t in ts]
                ax.plot(ts, ms, color=COLORS[b], linewidth=2.0, label=b)
            ax.set_title(arm, fontsize=10)
            ax.set_xlabel("votes spent")
            ax.grid(alpha=0.25, linewidth=0.5)
        for axi in leftmost:
            axi.set_ylabel("cost (lower is better)")
        axes[0].legend(title="band", fontsize=9)
        fig.suptitle(
            "Cost as votes are spent, by target size band"
            + (" — one line per run" if per_run else " — mean over runs"),
            fontsize=11,
        )
        fig.tight_layout()
        name = "cost_vs_votes_per_run.png" if per_run else "cost_vs_votes.png"
        fig.savefig(out / name, dpi=130)
        plt.close(fig)
        print("wrote", name)

    # 3: endpoint cost by band, per encoder
    fig, ax = plt.subplots(figsize=(6.4, 4.0))
    width = 0.8 / max(1, len(arms))
    for i, arm in enumerate(arms):
        xs = [j + i * width for j in range(len(BANDS))]
        ms = [mean_se(endpoint[(arm, b)])[0] for b in BANDS]
        es = [mean_se(endpoint[(arm, b)])[1] for b in BANDS]
        ax.bar(xs, ms, width=width * 0.9, yerr=es, capsize=3, label=arm)
    ax.set_xticks([j + 0.4 - width / 2 for j in range(len(BANDS))])
    ax.set_xticklabels(BANDS)
    ax.set_ylabel("cost at 150 votes")
    ax.set_xlabel("target size band")
    ax.set_title("Cost by target size, each encoder separately")
    ax.legend(fontsize=8)
    ax.grid(axis="y", alpha=0.25, linewidth=0.5)
    fig.tight_layout()
    fig.savefig(out / "cost_by_band.png", dpi=130)
    plt.close(fig)
    print("wrote cost_by_band.png")

    # 4: paired small - large, per class
    fig, ax = plt.subplots(figsize=(7.2, 4.2))
    classes = sorted({c for (_a, c, _s) in per_class})
    for i, arm in enumerate(arms):
        vals = []
        for c in classes:
            d = [
                v["small"] - v["large"]
                for (a, cc, _s), v in per_class.items()
                if a == arm and cc == c and "small" in v and "large" in v
            ]
            vals.append(mean_se(d)[0] if d else float("nan"))
        ax.plot(range(len(classes)), vals, "o-", markersize=4, linewidth=1.2, label=arm, alpha=0.85)
    ax.axhline(0, color="#444", linewidth=1)
    ax.set_xticks(range(len(classes)))
    ax.set_xticklabels(classes, rotation=45, ha="right", fontsize=8)
    ax.set_ylabel("cost(small) − cost(large)")
    ax.set_title("Paired size penalty per class (above zero = small is harder)")
    ax.legend(fontsize=8)
    ax.grid(alpha=0.25, linewidth=0.5)
    fig.tight_layout()
    fig.savefig(out / "size_penalty_per_class.png", dpi=130)
    plt.close(fig)
    print("wrote size_penalty_per_class.png")
    print(f"figures in {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
