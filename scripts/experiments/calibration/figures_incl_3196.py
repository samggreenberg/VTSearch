"""Figures for the Inclusion-knob study (#3196), from the analyzer's own CSVs.

Five figures, each answering something the tables cannot:

1. **where the flat band is** -- the share of steps whose admitted set moved at
   each stop of the knob, one line per head.  A pooled dead-step rate says how
   much of the slider is dead; only this says *which* part, and a band sitting
   around ``k = 0`` is a band under the user's thumb.
2. **what the slider is worth** -- mean admitted fraction across the knob, one
   line per head.  The distance between its ends *is* the knob's authority.
3. **the same, one line per cell** -- because a mean hides that some cells never
   move at all, and that spread is usually the real finding.
4. **by box-size band** -- the separability ladder the mechanism runs on: the
   tilt dies where the fitted components are cleanly separated, and #3255
   measured cost tripling from large targets to small.
5. **the acquisition offset's collapse** -- what #2896's gap across the slider
   is still worth, per stop, per head.

Generated by committed code from the same CSVs the tables read, so the numbers
in the report and the numbers in the pictures cannot drift apart.

Usage::

    python figures_incl_3196.py --analysis <dir> [--out <dir>]
"""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

from figures_overview import legend_in_spare, panel_grid  # noqa: E402

#: The shipped head first, and in a colour that reads as "this is the one that
#: ships" beside a muted reference.
HEADS = ("svm", "linear")
COLORS = {"svm": "#b91c1c", "linear": "#334155"}
LABELS = {"svm": "linear SVM (shipped)", "linear": "logistic (replaced)"}
BANDS = ("small", "medium", "large")
BAND_COLORS = {"small": "#c2410c", "medium": "#0f766e", "large": "#3730a3"}
DPI = 130


def _short(env: str) -> str:
    """``vg_scale/siglip+dinov3_patch/max_patch`` -> ``siglip+dinov3_patch / max_patch``."""
    parts = env.split("/")
    return " / ".join(parts[1:]) if len(parts) > 2 else env


def _envs(df: pd.DataFrame) -> list[str]:
    return sorted(df["env"].unique())


def _legend(fig, axes, spare, **kw) -> None:
    """Legend in a spare panel when the wrap left one, else under the figure.

    Never inside a panel: these panels are lines that run along the top or the
    bottom of their own axes, so an in-panel legend lands on the data exactly
    where the finding is.
    """
    if legend_in_spare(axes, spare, **kw):
        return
    handles, labels = axes[0].get_legend_handles_labels()
    if handles:
        fig.legend(handles, labels, loc="lower center", ncol=min(len(labels), 3), frameon=False, **kw)


def fig_flat_band(per_k: pd.DataFrame, incumbent: str, out: Path) -> None:
    sub = per_k[per_k["arm"] == incumbent]
    envs = _envs(sub)
    fig, axes, leftmost, spare = panel_grid(len(envs), 4.6, 3.4)
    for ax, env in zip(axes, envs, strict=False):
        for head in HEADS:
            s = sub[(sub["env"] == env) & (sub["head_arm"] == head)].sort_values("inclusion_k")
            if s.empty:
                continue
            ax.plot(s["inclusion_k"], s["moved_rate"], color=COLORS[head], label=LABELS[head], lw=2)
        ax.axvline(0, color="#9ca3af", lw=0.8, ls=":")
        ax.set_ylim(-0.02, 1.02)
        ax.set_title(_short(env), fontsize=9)
        ax.set_xlabel("inclusion k")
    for ax in leftmost:
        ax.set_ylabel("share of steps whose\nadmitted set moved")
    _legend(fig, axes, spare, fontsize=9)
    fig.suptitle("Where the Inclusion knob is dead, per head", fontsize=11)
    fig.tight_layout(rect=(0, 0.07, 1, 1))
    fig.savefig(out / "flat_band.png", dpi=DPI)
    plt.close(fig)


def fig_authority(per_k: pd.DataFrame, incumbent: str, out: Path) -> None:
    sub = per_k[per_k["arm"] == incumbent]
    envs = _envs(sub)
    fig, axes, leftmost, spare = panel_grid(len(envs), 4.6, 3.4)
    for ax, env in zip(axes, envs, strict=False):
        for head in HEADS:
            s = sub[(sub["env"] == env) & (sub["head_arm"] == head)].sort_values("inclusion_k")
            if s.empty:
                continue
            ax.plot(s["inclusion_k"], s["admitted_frac"], color=COLORS[head], label=LABELS[head], lw=2)
            ax.plot(
                s["inclusion_k"],
                s["fold_quantile"],
                color=COLORS[head],
                lw=1,
                ls="--",
                alpha=0.55,
                label=f"{LABELS[head]} — fold quantile",
            )
        ax.axvline(0, color="#9ca3af", lw=0.8, ls=":")
        ax.set_title(_short(env), fontsize=9)
        ax.set_xlabel("inclusion k")
    for ax in leftmost:
        ax.set_ylabel("admitted fraction")
    _legend(fig, axes, spare, fontsize=8)
    fig.suptitle("What dragging the slider is worth (solid), and what the rule asked for (dashed)", fontsize=10)
    fig.tight_layout(rect=(0, 0.12, 1, 1))
    fig.savefig(out / "knob_authority.png", dpi=DPI)
    plt.close(fig)


def fig_per_cell(cells: pd.DataFrame, incumbent: str, out: Path) -> None:
    """One marker per cell: a mean cannot show that some cells never move."""
    sub = cells[cells["arm"] == incumbent]
    envs = _envs(sub)
    fig, axes, leftmost, spare = panel_grid(len(envs), 4.6, 3.4)
    for ax, env in zip(axes, envs, strict=False):
        for i, head in enumerate(HEADS):
            s = sub[(sub["env"] == env) & (sub["head_arm"] == head)]
            if s.empty:
                continue
            jitter = (pd.Series(range(len(s))) % 7 - 3) / 40.0
            ax.scatter(
                [i] * len(s) + jitter.to_numpy(),
                s["admitted_span"].to_numpy(),
                s=14,
                alpha=0.6,
                color=COLORS[head],
                label=LABELS[head] if ax is axes[0] else None,
            )
            ax.hlines(float(s["admitted_span"].mean()), i - 0.25, i + 0.25, color="#111827", lw=2)
        ax.set_xticks(range(len(HEADS)))
        ax.set_xticklabels([LABELS[h] for h in HEADS], fontsize=7)
        ax.set_title(_short(env), fontsize=9)
    for ax in leftmost:
        ax.set_ylabel("admitted-fraction span\nover the whole knob (per cell)")
    _legend(fig, axes, spare, fontsize=8)
    fig.suptitle("Knob authority per cell — the bar is the mean", fontsize=11)
    fig.tight_layout(rect=(0, 0.07, 1, 1))
    fig.savefig(out / "authority_per_cell.png", dpi=DPI)
    plt.close(fig)


def fig_by_band(bands: pd.DataFrame, out: Path) -> None:
    """The separability ladder: does the band open where the target is easy?"""
    present = [b for b in BANDS if b in set(bands["band"])]
    if not present:
        return
    envs = _envs(bands)
    fig, axes, leftmost, spare = panel_grid(len(envs), 4.6, 3.4)
    width = 0.36
    for ax, env in zip(axes, envs, strict=False):
        for i, head in enumerate(HEADS):
            s = bands[(bands["env"] == env) & (bands["head_arm"] == head)].set_index("band")
            if s.empty:
                continue
            xs = [j + (i - 0.5) * width for j in range(len(present))]
            ax.bar(
                xs,
                [float(s["dead_step_rate"].get(b, float("nan"))) for b in present],
                width=width,
                color=COLORS[head],
                alpha=0.85,
                label=LABELS[head] if ax is axes[0] else None,
            )
        ax.set_xticks(range(len(present)))
        ax.set_xticklabels([f"{b} target" for b in present], fontsize=8)
        ax.set_ylim(0, 1)
        ax.set_title(_short(env), fontsize=9)
    for ax in leftmost:
        ax.set_ylabel("dead-step rate")
    _legend(fig, axes, spare, fontsize=8)
    fig.suptitle("Does the flat band follow target size? (box-size band = separability)", fontsize=10)
    fig.tight_layout(rect=(0, 0.07, 1, 1))
    fig.savefig(out / "flatness_by_band.png", dpi=DPI)
    plt.close(fig)


def fig_offset(gaps: pd.DataFrame, out: Path) -> None:
    envs = _envs(gaps)
    offset = int(gaps["offset"].iloc[0])
    fig, axes, leftmost, spare = panel_grid(len(envs), 4.6, 3.4)
    for ax, env in zip(axes, envs, strict=False):
        for head in HEADS:
            s = gaps[(gaps["env"] == env) & (gaps["head_arm"] == head)].sort_values("inclusion_k")
            if s.empty:
                continue
            ax.plot(s["inclusion_k"], s["collapse_rate"], color=COLORS[head], label=LABELS[head], lw=2)
        ax.axvline(0, color="#9ca3af", lw=0.8, ls=":")
        ax.set_ylim(-0.02, 1.02)
        ax.set_title(_short(env), fontsize=9)
        ax.set_xlabel("reporting inclusion k")
    for ax in leftmost:
        ax.set_ylabel(f"share of steps where the\noffset ({offset}) admits nothing new")
    _legend(fig, axes, spare, fontsize=9)
    fig.suptitle("What the acquisition offset is still worth (#2896's collapse)", fontsize=11)
    fig.tight_layout(rect=(0, 0.07, 1, 1))
    fig.savefig(out / "offset_collapse.png", dpi=DPI)
    plt.close(fig)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="#3196 report figures.")
    ap.add_argument("--analysis", required=True, help="directory analyze_incl_3196.py wrote")
    ap.add_argument("--out", default=None, help="figure directory (default: <analysis>/figures)")
    args = ap.parse_args(argv)

    analysis = Path(args.analysis)
    out = Path(args.out) if args.out else analysis / "figures"
    out.mkdir(parents=True, exist_ok=True)

    import json

    summary = json.loads((analysis / "incl3196_summary.json").read_text())
    incumbent = summary["incumbent"]

    per_k = pd.read_csv(analysis / "incl3196_per_k.csv")
    cells = pd.read_csv(analysis / "incl3196_per_cell.csv")
    bands = pd.read_csv(analysis / "incl3196_by_band.csv")
    fig_flat_band(per_k, incumbent, out)
    fig_authority(per_k, incumbent, out)
    fig_per_cell(cells, incumbent, out)
    fig_by_band(bands, out)
    gap_path = analysis / "incl3196_offset_gap.csv"
    if gap_path.exists():
        fig_offset(pd.read_csv(gap_path), out)
    print(f"figures -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
