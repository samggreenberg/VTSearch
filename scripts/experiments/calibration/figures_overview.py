"""Figures for the descriptive overview (#3156), from the cells the tables read.

Six figures, each answering something prose cannot. The deep run (60 seeds)
changes what is drawable: a per-cell stuck *rate* and an honest distribution
shape both need many runs per cell, and at three seeds neither existed.

1. **cost over votes spent, one line per mode** — what a user gets after N
   clicks, the axis they actually spend, with a band for the spread.
2. **the same, one line per run** — a mean hides that some runs never leave the
   floor, and that spread is the product problem.
3. **ECDF of cost at the deep step** — the honest shape. Where the curve is flat
   near 1.0 is the fraction of users the mode simply fails.
4. **what the cost is made of** — `oracle_cost` (the ranking's limit) stacked
   under `rule_inefficiency` and `calibration_shift` (the two halves of regret),
   per band. Different bars want different fixes.
5. **per-cell stuck rate** — the deep run's payoff: reliably hard cells separated
   from unlucky draws, all cells x modes at once.
6. **stuck rate by class and band** — which classes carry the size penalty, since
   a pooled mean can be produced by two classes out of twelve.

Generated by committed code so the numbers in the report and the numbers in the
pictures cannot drift apart.
"""

from __future__ import annotations

import argparse
import csv
import glob
import os
from collections import defaultdict
from pathlib import Path

BANDS = ("small", "medium", "large")
BAND_COLORS = {"small": "#c2410c", "medium": "#0f766e", "large": "#3730a3"}
MODE_COLORS = {
    # The region arm is the SigLIP+DINOv3 pair since #3276; the bare-DINOv3 key
    # stays so a figure re-made from an older grid keeps its colour and the two
    # are not confusable across reports.
    "siglip+dinov3_patch/max_patch": "#7c3aed",
    "dinov3_patch/max_patch": "#a78bfa",
    "siglip/whole_image": "#0891b2",
    "siglip2_l/whole_image": "#b45309",
    # The CLIP columns (#3292). `clip` is app-selectable; `clip_l` is
    # `eval_only` and is a reference column rather than a mode a user can pick,
    # which a figure cannot show -- so any report using these says which is
    # which. Named here rather than left to the `C{i}` fallback because that
    # fallback assigns by POSITION, so adding a column silently recolours the
    # ones after it and two reports stop being comparable by eye.
    "clip/whole_image": "#be123c",
    "clip_l/whole_image": "#4d7c0f",
}
DEEP = 150


def panel_grid(n: int, w: float, h: float, ncols_max: int = 3):
    """A wrapped grid of panels, plus the axes that need a y-label.

    One panel per mode in a single row was fine at three modes and stops being
    fine at five: the figure is then 23 inches wide, and a report renders it
    scaled to the column width, so each panel arrives at a fifth of the page and
    nothing in it can be read.  Wrapping at three keeps a panel the size it was
    drawn at whatever the mode count does next.

    Returns ``(fig, axes, leftmost)`` -- *axes* is exactly *n* visible axes in
    order, and *leftmost* is the first of each row, which is where a shared
    y-label belongs once there is more than one row.
    """
    import math

    import matplotlib.pyplot as plt  # noqa: PLC0415  (the backend is chosen by the caller)

    ncols = min(n, ncols_max)
    nrows = math.ceil(n / ncols)
    fig, grid = plt.subplots(nrows, ncols, figsize=(w * ncols, h * nrows), sharey=True, squeeze=False)
    flat = [a for row in grid for a in row]
    for a in flat[n:]:
        a.set_visible(False)
    return fig, flat[:n], [grid[r][0] for r in range(nrows)]


def band_of(c: str) -> str:
    return c.rsplit("@", 1)[1] if "@" in c else ""


def class_of(c: str) -> str:
    return c.rsplit("@", 1)[0]


def mean_se(xs):
    n = len(xs)
    if n == 0:
        return float("nan"), float("nan")
    m = sum(xs) / n
    if n < 2:
        return m, float("nan")
    v = sum((x - m) ** 2 for x in xs) / (n - 1)
    return m, (v / n) ** 0.5


def load(exp: str):
    cells = Path(exp) / "results" / "cells"
    rows = []
    for path in sorted(glob.glob(str(cells / "task_*.csv"))):
        if "__" in Path(path).name:
            continue
        try:
            with open(path, newline="") as fh:
                rows.extend(list(csv.DictReader(fh)))
        except (OSError, csv.Error):
            continue
    return rows


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--exp", default=f"/expscratch/{os.environ.get('USER', 'sgreenberg')}/scale-3156-final")
    ap.add_argument("--out", default="")
    ap.add_argument("--floor", type=float, default=0.9)
    ap.add_argument("--max-run-lines", type=int, default=900, help="cap on figure 2's spaghetti, for legibility")
    args = ap.parse_args()

    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    out = Path(args.out or (Path(args.exp) / "figures"))
    out.mkdir(parents=True, exist_ok=True)
    rows = load(args.exp)
    if not rows:
        print(f"no rows under {args.exp}")
        return 1

    def mode(r):
        return f"{r.get('embedder', '')}/{r.get('style', '')}".strip("/")

    modes = sorted({mode(r) for r in rows})
    color = {m: MODE_COLORS.get(m, f"C{i}") for i, m in enumerate(modes)}

    # (mode, cat, seed) -> [(t, cost, oracle, rule, cal)]
    runs: dict[tuple, list] = defaultdict(list)
    for r in rows:
        try:
            t = int(r["t"])
            c = float(r["cost"])
        except (KeyError, ValueError, TypeError):
            continue

        def g(key):
            try:
                return float(r[key])
            except (KeyError, ValueError, TypeError):
                return float("nan")

        runs[(mode(r), r["category"], r["seed"])].append(
            (t, c, g("oracle_cost"), g("rule_inefficiency"), g("calibration_shift"))
        )
    for v in runs.values():
        v.sort()
    print(f"{len(rows)} rows, {len(runs)} runs, {len(modes)} modes -> {out}")

    steps = sorted({t for v in runs.values() for t, *_ in v})

    def cost_at(series, s):
        best = None
        for t, c, *_ in series:
            if t <= s:
                best = c
        return best

    # --- 1. cost over votes, per mode ---------------------------------------
    fig, ax = plt.subplots(figsize=(7.0, 4.4))
    for m in modes:
        sel = [v for k, v in runs.items() if k[0] == m]
        xs, ys, los, his = [], [], [], []
        for s in steps:
            vals = [c for c in (cost_at(v, s) for v in sel) if c is not None]
            if len(vals) < 5:
                continue
            mu, se = mean_se(vals)
            xs.append(s)
            ys.append(mu)
            los.append(mu - se)
            his.append(mu + se)
        ax.plot(xs, ys, label=m, color=color[m], lw=2)
        ax.fill_between(xs, los, his, color=color[m], alpha=0.18, lw=0)
    ax.set_xlabel("votes spent")
    ax.set_ylabel("cost (lower is better)")
    ax.set_title("What a user gets for their clicks (mean ±SE over runs)")
    ax.legend(fontsize=8)
    ax.grid(alpha=0.25)
    fig.tight_layout()
    fig.savefig(out / "cost_over_votes.png", dpi=130)
    plt.close(fig)

    # --- 2. the same, one line per run --------------------------------------
    fig, axes, leftmost = panel_grid(len(modes), 4.6, 4.2)
    for axi, m in zip(axes, modes):
        sel = [v for k, v in runs.items() if k[0] == m]
        step = max(1, len(sel) // args.max_run_lines)
        drawn = sel[::step]
        for v in drawn:
            axi.plot([t for t, *_ in v], [c for _, c, *_ in v], color=color[m], alpha=0.06, lw=0.8)
        axi.axhline(args.floor, color="#a3341f", ls="--", lw=1)
        shown = f"{len(drawn)} of {len(sel)}" if step > 1 else f"all {len(sel)}"
        axi.set_title(f"{m}\n({shown} runs)", fontsize=9)
        axi.set_xlabel("votes spent")
        axi.grid(alpha=0.2)
    for axi in leftmost:
        axi.set_ylabel("cost")
    fig.suptitle(f"Every run separately — the dashed line is the {args.floor} 'never got going' floor", fontsize=10)
    fig.tight_layout()
    fig.savefig(out / "cost_per_run.png", dpi=130)
    plt.close(fig)

    # --- 3. ECDF of deep cost ------------------------------------------------
    fig, ax = plt.subplots(figsize=(6.6, 4.2))
    for m in modes:
        vals = sorted(c for c in (cost_at(v, DEEP) for k, v in runs.items() if k[0] == m) if c is not None)
        if not vals:
            continue
        ys = [(i + 1) / len(vals) for i in range(len(vals))]
        ax.step(vals, ys, where="post", color=color[m], lw=2, label=f"{m} (n={len(vals)})")
    ax.axvline(args.floor, color="#a3341f", ls="--", lw=1)
    ax.set_xlabel(f"cost at {DEEP} votes")
    ax.set_ylabel("fraction of runs at or below")
    ax.set_title("The shape a mean hides")
    ax.legend(fontsize=8, loc="lower right")
    ax.grid(alpha=0.25)
    fig.tight_layout()
    fig.savefig(out / "cost_ecdf.png", dpi=130)
    plt.close(fig)

    # --- 4. what the cost is made of ----------------------------------------
    fig, axes, leftmost = panel_grid(len(modes), 4.3, 4.2)
    for axi, m in zip(axes, modes):
        o_, r_, c_ = [], [], []
        for b in BANDS:
            sel = [v for k, v in runs.items() if k[0] == m and band_of(k[1]) == b]
            last = [v[-1] for v in sel if v and v[-1][0] <= DEEP]
            o_.append(mean_se([x[2] for x in last if x[2] == x[2]])[0])
            r_.append(mean_se([x[3] for x in last if x[3] == x[3]])[0])
            c_.append(mean_se([x[4] for x in last if x[4] == x[4]])[0])
        axi.bar(BANDS, o_, color="#334155", label="oracle_cost (ranking's limit)")
        axi.bar(BANDS, r_, bottom=o_, color="#0891b2", label="rule_inefficiency")
        axi.bar(BANDS, c_, bottom=[a + b for a, b in zip(o_, r_)], color="#f59e0b", label="calibration_shift")
        axi.set_title(m, fontsize=9)
        axi.grid(alpha=0.2, axis="y")
    for axi in leftmost:
        axi.set_ylabel(f"cost at {DEEP} votes")
    axes[-1].legend(fontsize=7.5)
    fig.suptitle("What the cost is made of — the dark block is what no cut rule can fix", fontsize=10)
    fig.tight_layout()
    fig.savefig(out / "cost_composition.png", dpi=130)
    plt.close(fig)

    # --- 5. per-cell stuck rate ---------------------------------------------
    per: dict[tuple, list] = defaultdict(list)
    for k, v in runs.items():
        c = cost_at(v, DEEP)
        if c is not None:
            per[(k[1], k[0])].append(c)
    cats = sorted(
        {k[0] for k in per}, key=lambda c: (BANDS.index(band_of(c)) if band_of(c) in BANDS else 9, class_of(c))
    )
    fig, ax = plt.subplots(figsize=(1.9 * len(modes) + 4.2, 0.30 * len(cats) + 1.8))
    grid = [
        [
            (sum(1 for x in per.get((c, m), []) if x >= args.floor) / len(per[(c, m)]))
            if per.get((c, m))
            else float("nan")
            for m in modes
        ]
        for c in cats
    ]
    im = ax.imshow(grid, cmap="magma_r", vmin=0, vmax=1, aspect="auto")
    ax.set_xticks(range(len(modes)))
    ax.set_xticklabels([m.split("/")[0] for m in modes], fontsize=8)
    ax.set_yticks(range(len(cats)))
    ax.set_yticklabels(cats, fontsize=7)
    for i, c in enumerate(cats):
        for j, m in enumerate(modes):
            n = len(per.get((c, m), []))
            if n:
                v = grid[i][j]
                ax.text(j, i, f"{v:.2f}", ha="center", va="center", fontsize=6, color="w" if v > 0.5 else "#222")
    fig.colorbar(im, ax=ax, label=f"fraction of runs with cost >= {args.floor}")
    ax.set_title("Reliably hard, or an unlucky seed?", fontsize=10)
    fig.tight_layout()
    fig.savefig(out / "stuck_rate_per_cell.png", dpi=130)
    plt.close(fig)

    # --- 6. stuck rate by class and band ------------------------------------
    classes = sorted({class_of(c) for c in cats})
    fig, ax = plt.subplots(figsize=(8.4, 4.4))
    w = 0.26
    for bi, b in enumerate(BANDS):
        ys = []
        for cl in classes:
            vals = [x for m in modes for x in per.get((f"{cl}@{b}", m), [])]
            ys.append(sum(1 for x in vals if x >= args.floor) / len(vals) if vals else 0.0)
        ax.bar([i + (bi - 1) * w for i in range(len(classes))], ys, width=w, label=b, color=BAND_COLORS[b])
    ax.set_xticks(range(len(classes)))
    ax.set_xticklabels(classes, rotation=45, ha="right", fontsize=8)
    ax.set_ylabel(f"fraction of runs with cost >= {args.floor}")
    ax.set_title(f"Which classes carry the size penalty (pooled over all {len(modes)} modes)")
    ax.legend(fontsize=8)
    ax.grid(alpha=0.25, axis="y")
    fig.tight_layout()
    fig.savefig(out / "stuck_rate_by_class.png", dpi=130)
    plt.close(fig)

    for p in sorted(out.glob("*.png")):
        print(f"  {p.name}  {p.stat().st_size // 1024} KB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
