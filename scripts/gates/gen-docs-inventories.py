def tracked_markdown_files() -> list[Path]:
    out = subprocess.run(["git", "ls-files", "*.md"], cwd=REPO_ROOT, capture_output=True, text=True, check=True).stdout
    return [REPO_ROOT / line for line in out.splitlines() if line]


def regenerate_file(path: Path) -> tuple[str, str, list[str]]:
    """Return (old_text, new_text, region_ids) for *path*."""
    old = path.read_text(encoding="utf-8")
    ids: list[str] = []

    def _sub(match: re.Match) -> str:
        region_id = match.group("id")
        ids.append(region_id)
        body = build_region(region_id)
        return f"{match.group(1)}{NOTE}\n\n{body}\n\n{match.group(4)}"

    new = REGION_RE.sub(_sub, old)
    # Any marker the region regex did not consume is a mismatched or unclosed
    # marker pair — fail loudly rather than silently leaving it un-generated.
    leftover = len(ANY_MARKER_RE.findall(new)) - 2 * len(ids)
    if leftover:
        raise SystemExit(
            f"ERROR: {path.relative_to(REPO_ROOT)} has unmatched GENERATED markers "
            f"(a BEGIN without its END, or mismatched region ids)."
        )
    return old, new, ids


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if any generated region is stale")
    args = parser.parse_args()

    seen_regions: set[str] = set()
    stale: list[Path] = []
    for path in tracked_markdown_files():
        text = path.read_text(encoding="utf-8")
        if "<!-- BEGIN GENERATED:" not in text:
            continue
        old, new, ids = regenerate_file(path)
        seen_regions.update(ids)
        if new != old:
            rel = path.relative_to(REPO_ROOT)
            if args.check:
                stale.append(path)
                diff = difflib.unified_diff(
                    old.splitlines(keepends=True), new.splitlines(keepends=True), str(rel), str(rel)
                )
                sys.stdout.writelines(list(diff)[:60])
            else:
                path.write_text(new, encoding="utf-8")
                print(f"regenerated {rel}")

    # Coverage invariant: every media type that declares demo datasets must
    # have its demos:<type_id> region somewhere in the docs.
    missing = [
        f"demos:{t.type_id}" for t in _media_types() if t.demo_datasets and f"demos:{t.type_id}" not in seen_regions
    ]
    if missing:
        print(
            "ERROR: media types with demo datasets but no generated docs region: "
            + ", ".join(missing)
            + " (add the region to docs/demos.md)"
        )
        return 1

    if stale:
        print()
        print("Generated doc inventories are stale in:")
        for path in stale:
            print(f"  {path.relative_to(REPO_ROOT)}")
        print(REGEN_HINT)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
