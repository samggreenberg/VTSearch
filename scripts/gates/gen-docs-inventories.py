#!/usr/bin/env python3
"""Generate registry inventories embedded in the documentation.

Hand-maintained copies of registry contents (embedders, plugin families,
demo datasets, converters, ...) were the single most repeated documentation
defect: roughly ten documents re-tabulated the same registries by hand and
disagreed with the code and with each other.  This script makes those tables
*generated*: a doc marks a region with

    <!-- BEGIN GENERATED: <region-id> -->
    ...                                          (content owned by this script)
    <!-- END GENERATED: <region-id> -->

and this script rewrites everything between the markers from the live
registries (``vtscore.plugins.inventory``, ``vtscore.media``, the demo-dataset
declarations on each media type).  A generated table cannot be fixed *wrong*,
and a new plugin/demo/family shows up in the docs by re-running the generator
instead of by remembering ten call sites.

Usage:
    python scripts/gates/gen-docs-inventories.py            # rewrite regions in place
    python scripts/gates/gen-docs-inventories.py --check    # exit 1 if anything is stale

``--check`` runs as part of ``./run-tests.sh`` (same shape as the OpenAPI
snapshot gate): regenerate, diff against the committed docs, fail with the
regeneration command on mismatch.

Region ids
----------
Fixed ids: ``embedders``, ``embedder-files``, ``embedder-dims``,
``media-types``, ``plugin-families``, ``achievements`` (the achievement
catalog, ``vtsearch.achievements_catalog``), ``lessons-index`` and
``scratch-deletions-index`` (the last two index ``scripts/experiments/lessons/``
and ``scripts/experiments/scratch-deletions/`` off the filesystem rather than a
registry).
Parameterised ids:
``plugins:<family>`` (roster of one plugin family, e.g.
``plugins:converters``) and ``demos:<type_id>`` (demo-dataset table of one
media type, e.g. ``demos:audio``).  An unknown id is a hard error, and every
media type that declares demo datasets must have its ``demos:<type_id>``
region somewhere in the scanned docs, so new media types cannot ship
undocumented demos.

Every tracked ``*.md`` file is scanned, so a doc can adopt a region without
touching this script.
"""

from __future__ import annotations

import argparse
import difflib
import re
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]

REGION_RE = re.compile(
    r"(<!-- BEGIN GENERATED: (?P<id>[a-z0-9_:-]+) -->\n)(?P<body>.*?)(<!-- END GENERATED: (?P=id) -->)",
    re.DOTALL,
)
ANY_MARKER_RE = re.compile(r"<!-- (?:BEGIN|END) GENERATED: [a-z0-9_:-]+ -->")

NOTE = (
    "<!-- Generated by scripts/gates/gen-docs-inventories.py; do not edit by hand. "
    "Refresh with: python scripts/gates/gen-docs-inventories.py -->"
)

REGEN_HINT = "Run 'python scripts/gates/gen-docs-inventories.py' and commit the result."


def _table(headers: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Registry access (imported lazily so --help stays instant)
# ---------------------------------------------------------------------------


def _inventory() -> dict:
    """Full plugin inventory: library families plus the app-tier settings families."""
    from vtsearch.seam_wiring import register_app_plugin_families
    from vtscore.plugins.inventory import gather_plugins

    register_app_plugin_families()
    return gather_plugins()


def _sorted_embedders() -> list:
    from vtscore.media import all_embedders

    return sorted(all_embedders(), key=lambda e: (e.media_type_id, not e.is_default, e.name))


def _media_types() -> list:
    from vtscore.media import all_types

    return sorted(all_types(), key=lambda t: t.type_id)


# ---------------------------------------------------------------------------
# Region builders
# ---------------------------------------------------------------------------


def build_embedders() -> str:
    """Full embedder roster: identity, model, dimension, capability notes."""
    rows = []
    for e in _sorted_embedders():
        notes = []
        if e.is_default:
            notes.append("**default** for its media type")
        if e.eval_only:
            notes.append("**evaluation only** — registered, but withheld from the app's pickers")
        if not e.supports_text:
            notes.append("no text queries")
        if e.supports_patch_regions:
            notes.append("patch grid (region-aware)")
        if e.supports_geometric_verification:
            notes.append("geometric verification")
        if e.license_notice:
            notes.append("restricted model license")
        rows.append(
            [
                f"`{e.media_type_id}`",
                f"`{e.name}`",
                e.display_name,
                f"`{e.model_id}`" if e.model_id else "—",
                str(e.embedding_dim) if e.embedding_dim else "—",
                "; ".join(notes) or "—",
            ]
        )
    return _table(["Media type", "Embedder", "Display name", "Model", "Dim", "Notes"], rows)


def build_embedder_files() -> str:
    """File/class map of every registered embedder (for the extending guide)."""
    rows = []
    for e in _sorted_embedders():
        module = type(e).__module__
        path = module.replace(".", "/") + ".py"
        rows.append(
            [
                f"`{path.removeprefix('vtscore/media/')}`",
                f"`{type(e).__name__}`",
                f"`{e.name}`",
                f"`{e.media_type_id}`",
                "✅" if e.is_default else "",
            ]
        )
    return _table(["File (under `vtscore/media/`)", "Class", "Embedder", "Media type", "Default"], rows)


def build_embedder_dims() -> str:
    rows = [
        [f"`{e.name}`", f"`{e.media_type_id}`" + (" (default)" if e.is_default else ""), str(e.embedding_dim)]
        for e in _sorted_embedders()
    ]
    return _table(["Embedder", "Media type", "D"], rows)


def build_media_types() -> str:
    """Media types with their default embedder and the alternatives."""
    embedders = _sorted_embedders()
    rows = []
    for t in _media_types():
        of_type = [e for e in embedders if e.media_type_id == t.type_id]
        default = next((e for e in of_type if e.is_default), of_type[0] if len(of_type) == 1 else None)
        alternatives = [e for e in of_type if e is not default]
        rows.append(
            [
                f"`{t.type_id}`",
                f"`{default.name}` ({default.display_name})" if default else "— (convert first)",
                f"`{default.model_id}`" if default and default.model_id else "—",
                ", ".join(f"`{e.name}`" for e in alternatives) or "—",
            ]
        )
    return _table(["Media type", "Default embedder", "Model", "Alternative embedders"], rows)


#: Where each ``PluginRegistry`` family lives: its ``list_*`` accessor and the
#: base class a plugin subclasses, both as ``"module:attribute"``.  The package,
#: sentinel and entry-point group are read off the accessor's live registry, so
#: they cannot disagree with the code; the base classes are imported, so a
#: rename fails ``--check`` instead of leaving a dead name in the docs.
REGISTRY_FAMILIES: dict[str, tuple[str, tuple[str, ...]]] = {
    "importers": (
        "vtscore.datasets.importers:list_importers",
        ("vtscore.datasets.importers.base:ImporterBase", "vtscore.datasets.importers.base:DatasetImporter"),
    ),
    "datasource_importers": (
        "vtscore.datasource_importers:list_datasource_importers",
        ("vtscore.datasource_importers.base:DataSourceImporter",),
    ),
    "exporters": ("vtscore.exporters:list_exporters", ("vtscore.exporters.base:ResultsExporter",)),
    "label_importers": (
        "vtscore.labels.importers:list_label_importers",
        ("vtscore.labels.importers.base:LabelImporter",),
    ),
    "seed_importers": ("vtscore.seed_importers:list_seed_importers", ("vtscore.seed_importers.base:SeedImporter",)),
    "labelset_sources": (
        "vtscore.labels.sources:list_labelset_sources",
        ("vtscore.labels.sources.base:LabelsetSource",),
    ),
    "converters": ("vtscore.converters:list_converters", ("vtscore.converters.base:MediaConverter",)),
    "media_sources": ("vtscore.datasets.sources:list_media_sources", ("vtscore.datasets.sources.base:MediaSource",)),
    "settings_importers": (
        "vtsearch.settings_io.importers:list_settings_importers",
        ("vtsearch.settings_io.importers.base:SettingsImporter",),
    ),
    "settings_exporters": (
        "vtsearch.settings_io.exporters:list_settings_exporters",
        ("vtsearch.settings_io.exporters.base:SettingsExporter",),
    ),
    "settings_sources": (
        "vtsearch.settings_io.sources:list_settings_sources",
        ("vtsearch.settings_io.sources.base:SettingsSource",),
    ),
}

#: The ``vtscore.media`` registries are not ``PluginRegistry`` families: they
#: scan ``vtscore/media/`` sub-packages for a sentinel and have no entry-point
#: group, so a third party calls a ``register`` function instead.  Stated as
#: ``(sentinel, base class, register function)``; the last two are imported.
MEDIA_FAMILIES: dict[str, tuple[str, str, str]] = {
    "media_types": ("MEDIA_TYPE", "vtscore.media:MediaType", "vtscore.media:register"),
    "embedders": ("EMBEDDER", "vtscore.media:MediaEmbedder", "vtscore.media:register_embedder"),
    "clippers": ("CLIPPERS", "vtscore.media:MediaClipper", "vtscore.media:register_clipper"),
    "cleaners": ("CLEANERS", "vtscore.media:MediaCleaner", "vtscore.media:register_cleaner"),
}


def _resolve(path: str):
    """Import ``"module:attribute"`` and return the attribute."""
    import importlib

    module, _, attr = path.partition(":")
    return getattr(importlib.import_module(module), attr)


def _family_location(fam: str, built_in: list[str]) -> tuple[str, str, str, str]:
    """``(package, sentinel, base class, third-party hook)`` cells for one family."""
    import inspect

    from vtscore.plugins import PluginRegistry

    if fam in REGISTRY_FAMILIES:
        accessor_path, base_paths = REGISTRY_FAMILIES[fam]
        accessor = _resolve(accessor_path)
        # make_plugin_registry hands out the registry's bound ``list``.
        registry = getattr(accessor, "__self__", None)
        if not isinstance(registry, PluginRegistry):
            raise SystemExit(f"{accessor_path} is not a PluginRegistry accessor; fix REGISTRY_FAMILIES[{fam!r}].")
        if [getattr(p, "name", repr(p)) for p in accessor()] != built_in:
            raise SystemExit(f"{accessor_path} does not list family {fam!r}'s plugins; fix REGISTRY_FAMILIES.")
        group = registry.entry_point_group
        package, sentinel = registry.package, registry.sentinel
        hook = f"entry-point group `{group}`" if group else "—"
    elif fam in MEDIA_FAMILIES:
        sentinel, base_path, register_path = MEDIA_FAMILIES[fam]
        base_paths = (base_path,)
        register = _resolve(register_path)
        package = "vtscore.media"
        hook = f"call `{register.__module__}.{register.__name__}()`"
    else:
        raise SystemExit(f"plugin family {fam!r} has no entry in REGISTRY_FAMILIES or MEDIA_FAMILIES; add one.")
    bases = [_resolve(p) for p in base_paths]
    for path, base in zip(base_paths, bases):
        if not inspect.isclass(base):
            raise SystemExit(f"{path} is not a class; fix the base class for family {fam!r}.")
    return f"`{package}`", f"`{sentinel}`", " / ".join(f"`{b.__name__}`" for b in bases), hook


def build_plugin_families() -> str:
    """Family table plus the counting rule, so prose never states a bare number."""
    inv = _inventory()
    from vtscore.plugins.inventory import FAMILIES  # snapshot after app registration

    app_families = {"settings_importers", "settings_exporters", "settings_sources"}
    library = [f for f in FAMILIES if f not in app_families]
    app = [f for f in FAMILIES if f in app_families]

    stale = (set(REGISTRY_FAMILIES) | set(MEDIA_FAMILIES)) - set(FAMILIES)
    if stale:
        raise SystemExit(
            f"no registered plugin family {sorted(stale)}; drop it from REGISTRY_FAMILIES / MEDIA_FAMILIES."
        )

    # The label lives on the FamilyProvider; reach it through the registry.
    from vtscore.plugins import inventory as _inv_mod

    def label(fam: str) -> str:
        provider = _inv_mod._FAMILIES_REGISTRY.get(fam)
        return provider.label if provider is not None else fam

    rows = []
    for fam in FAMILIES:
        entries = inv.get(fam, [])
        rows.append(
            [
                f"{label(fam)} (`{fam}`)",
                "app" if fam in app_families else "library",
                *_family_location(fam, [e.name for e in entries]),
                str(len(entries)),
            ]
        )
    counting_rule = (
        f"A **plugin family** is a registry enumerated by `vtscore.plugins.inventory` "
        f"(`python app.py --list-plugins`): {len(library)} library families self-register "
        f"when the library imports, and {len(app)} app-tier families (settings "
        f"importers/exporters/sources) are added by "
        f"`vtsearch.seam_wiring.register_app_plugin_families()` at app startup — "
        f"{len(FAMILIES)} in total. Counts below are the built-in plugins shipped "
        f"in-tree; third-party entry-point plugins add to them."
    )
    columns = (
        "Package, sentinel and entry-point group are read off each family's live "
        "`PluginRegistry`. The four media registries are not `PluginRegistry` families: "
        "they scan `vtscore/media/` sub-packages, and out-of-tree code calls the "
        "`register*` function named in the table instead of declaring an entry point."
    )
    headers = ["Family", "Tier", "Package", "Sentinel", "Base class", "Third-party hook", "Built-in plugins"]
    return counting_rule + "\n\n" + _table(headers, rows) + "\n\n" + columns


def build_plugin_family_roster(family: str) -> str:
    """Roster of one plugin family: name, display name, description."""
    inv = _inventory()
    if family not in inv:
        raise KeyError(f"unknown plugin family {family!r}; known: {', '.join(sorted(inv))}")
    entries = sorted(inv[family], key=lambda e: e.name)
    if family == "converters":
        rows = [
            [
                f"`{e.name}`",
                f"`{e.extra.get('source_type', '?')}` → `{e.extra.get('target_type', '?')}`",
                e.display_name,
                e.description,
            ]
            for e in entries
        ]
        return _table(["Converter", "Conversion", "Display name", "Description"], rows)
    rows = [[f"`{e.name}`", e.display_name, e.description] for e in entries]
    return _table(["Name", "Display name", "Description"], rows)


def build_demos(type_id: str) -> str:
    """Demo-dataset table for one media type, display names and sizes included.

    The display name is the label the in-app Demo catalogue shows ("ESC-50 (S)"),
    so a reader can match a row to what they see there; the id is what the CLI
    and the API take.
    """
    types = {t.type_id: t for t in _media_types()}
    if type_id not in types:
        raise KeyError(f"unknown media type {type_id!r}; known: {', '.join(sorted(types))}")
    demos = types[type_id].demo_datasets
    rows = []
    for d in demos:
        size = f"~{d.download_size_mb:g} MB" if d.download_size_mb else "—"
        rows.append([f"**{d.id}**", d.label, d.description, size])
    return _table(["Demo", "Display name", "Description", "Download"], rows)


def build_achievements() -> str:
    """The achievement catalog: what each entry counts, and the threshold that reaches each tier."""
    from vtsearch.achievements_catalog import ACHIEVEMENTS, TIER_NAMES

    rows = [[f"**{a['name']}**", a["description"], *(f"{n:,}" for n in a["tiers"])] for a in ACHIEVEMENTS]
    return _table(["Achievement", "What it counts", *TIER_NAMES], rows)


LESSONS_DIR = REPO_ROOT / "scripts" / "experiments" / "lessons"
LESSON_TITLE_RE = re.compile(r"^# (?P<date>\d{4}-\d{2}-\d{2})\s*—\s*(?P<title>.+)$")


def _newest_first(directory: Path) -> list[Path]:
    """The ``YYYY-MM-DD-slug.md`` files in *directory*: newest day first, and
    alphabetical by slug within a day."""
    return sorted(directory.glob("*.md"), key=lambda p: (p.name[:10], [-ord(c) for c in p.name[10:]]), reverse=True)


def build_lessons_index() -> str:
    """Index of `scripts/experiments/lessons/`, newest first.

    One incident per file is what keeps concurrent experiment branches from
    conflicting: two studies each recording a lesson add two *different* files
    rather than two appends to the same end of one.  This index is the price —
    it is the one shared line, which is why it is generated: if two branches do
    collide here, re-run the generator rather than merging the table by hand.
    """
    rows = []
    # Newest day first; within a day, alphabetical, because the flat file it
    # replaced recorded no finer ordering than the date.
    for path in _newest_first(LESSONS_DIR):
        first = path.read_text(encoding="utf-8").splitlines()[0]
        match = LESSON_TITLE_RE.match(first)
        if not match:
            raise SystemExit(
                f"ERROR: {path.relative_to(REPO_ROOT)} must start with '# YYYY-MM-DD — title'; found {first!r}"
            )
        title = match.group("title")
        issues = sorted(set(re.findall(r"#(\d+)", title)), key=int)
        # The issue numbers are pulled out into their own column, so strip the
        # now-duplicated trailing "(#1234)" the older titles carry.
        stripped = re.sub(r"\s*\(#[\d\s/#]+\)\s*$", "", title).strip()
        rows.append(
            [
                match.group("date"),
                f"[{stripped}](lessons/{path.name})",
                ", ".join(f"#{n}" for n in issues) or "—",
            ]
        )
    return _table(["Date", "Lesson", "Issue"], rows)


SCRATCH_DELETIONS_DIR = REPO_ROOT / "scripts" / "experiments" / "scratch-deletions"
SCRATCH_DELETION_TITLE_RE = re.compile(r"^# (?P<date>\d{4}-\d{2}-\d{2}):\s*(?P<title>.+)$")


def build_scratch_deletions_index() -> str:
    """Index of `scripts/experiments/scratch-deletions/`, newest first.

    The same shape as :func:`build_lessons_index`, for the same reason: one
    cleanup per file, so two sessions recording deletes add two files instead of
    two sections at the top of one.  The title is the heading verbatim; it
    already names the size and the issues, so neither gets a column.
    """
    rows = []
    # Within a day, alphabetical by slug.  The entries split out of the flat file
    # were given slugs that reproduce its newest-first order for the days that
    # had more than one.
    for path in _newest_first(SCRATCH_DELETIONS_DIR):
        first = path.read_text(encoding="utf-8").splitlines()[0]
        match = SCRATCH_DELETION_TITLE_RE.match(first)
        if not match:
            raise SystemExit(
                f"ERROR: {path.relative_to(REPO_ROOT)} must start with '# YYYY-MM-DD: title'; found {first!r}"
            )
        if match.group("date") != path.name[:10]:
            raise SystemExit(
                f"ERROR: {path.relative_to(REPO_ROOT)} is dated {match.group('date')} in its heading "
                f"but {path.name[:10]} in its name; the index sorts by the name"
            )
        rows.append([match.group("date"), f"[{match.group('title')}](scratch-deletions/{path.name})"])
    return _table(["Date", "Cleanup"], rows)


def build_region(region_id: str) -> str:
    fixed = {
        "embedders": build_embedders,
        "embedder-files": build_embedder_files,
        "embedder-dims": build_embedder_dims,
        "media-types": build_media_types,
        "plugin-families": build_plugin_families,
        "achievements": build_achievements,
        "lessons-index": build_lessons_index,
        "scratch-deletions-index": build_scratch_deletions_index,
    }
    if region_id in fixed:
        return fixed[region_id]()
    if region_id.startswith("plugins:"):
        return build_plugin_family_roster(region_id.removeprefix("plugins:"))
    if region_id.startswith("demos:"):
        return build_demos(region_id.removeprefix("demos:"))
    raise KeyError(f"no builder for generated region {region_id!r}")


