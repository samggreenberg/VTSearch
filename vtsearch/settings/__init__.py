"""Persistent settings for VTSearch.

Settings are split across two tiers:

* **Server tier** - shared, single-file settings used to bring the
  process up: dataset/detector directories, concurrency limits, the
  autoload-embedder / AutoFind detector lists. Stored in
  ``data/settings.json`` (path = :data:`~vtsearch.settings.tiers.SETTINGS_PATH`).
  Loaded once at startup, before any user has logged in.
* **Per-user tier** - every other key (preferences, autopilot config,
  per-side view modes, the ``settings_source`` sync target). Stored in
  ``<get_user_data_dir(user)>/user_settings.json``. Resolved per-request
  via :func:`~vtsearch.auth.get_current_user`.

The package exposes one ``get_<key>`` / ``set_<key>`` accessor pair per setting;
routing between tiers is internal. Auto-save on mutation and auto-sync to the
configured ``settings_source`` are unchanged in shape; the sync source is
per-user and triggers only on per-user writes.

The package
-----------

``vtsearch.settings`` is the settings API: import from here.  The accessors a
factory builds - one ``get_<key>`` / ``set_<key>`` / ``validate_<key>`` per field
of the two models, and the six per-side pairs - are generated and installed in
this module; everything else is re-exported from the module that implements
it.  The modules are layered, each reading only from those above it:

* :mod:`~vtsearch.settings.models` - the two pydantic models, the source of
  truth for every key's type, default and range.
* :mod:`~vtsearch.settings.admin_overrides` - one descriptor per admin override
  (its flag, env var, validator, and how it combines with the setting).
* :mod:`~vtsearch.settings.schema` - each key's tier, the defaults, and checking
  one value.
* :mod:`~vtsearch.settings.store` - the persistence engine: cross-process file
  locking, the caches, the source-sync state machine.
* :mod:`~vtsearch.settings.tiers` - the settings files' paths, the caches and
  their lock, the engine instance, and reading or writing one key.
* :mod:`~vtsearch.settings.accessors` - the accessor factories, the accessors
  written out by hand, and the whole-dict reads.
* :mod:`~vtsearch.settings.overrides` - the admin overrides in force and the
  plugins they hide.
* :mod:`~vtsearch.settings.sync` - the one rule for a per-user write from a
  ``PUT``, an import or a sync, and the binding to a settings source.

The last three call generated accessors, so they reach them through this
package; it imports :mod:`~vtsearch.settings.overrides` and
:mod:`~vtsearch.settings.sync` only once those exist.

**Patch the module that defines the name.**  A caller outside the package
resolves ``vtsearch.settings.X`` when it runs, so patching the package reaches
it - but a function inside a submodule does not look there.  Within the
package, a module calls another module's functions through that module
(``tiers._read_value(...)``, ``settings.get_beta()``), so a stub installed on
the defining module reaches every caller; a call inside one module resolves
that module's own global.  So stubbing ``get_effective_hidden_plugins`` for
:func:`filter_visible_plugins` means patching
:mod:`vtsearch.settings.overrides` (patching it here is silently ignored), and
stubbing ``_sync_to_source`` means patching :mod:`vtsearch.settings.tiers`.  The
generated accessors are defined here, so ``vtsearch.settings.get_beta`` is the
one target for them.  Private names, and the paths
:mod:`~vtsearch.settings.tiers` rebinds at run time (``SETTINGS_PATH``), are not
re-exported: read and patch them on the module that owns them.
"""

