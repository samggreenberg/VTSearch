def __getattr__(name: str) -> Any:
    # PEP 562 - expose ``_SERVER_DEFAULTS`` / ``_USER_DEFAULTS`` / ``_DEFAULTS``
    # as attributes for external readers (tests, future callers) without
    # forcing the eager pydantic instantiation at module load.  A module
    # ``__getattr__`` also lets type-checkers resolve any attribute of this
    # package, which is how the generated ``validate_<key>`` functions (which
    # have no stubs) type-check at their call sites.
    if name == "_SERVER_DEFAULTS":
        return schema._server_defaults()
    if name == "_USER_DEFAULTS":
        return schema._user_defaults()
    if name == "_DEFAULTS":
        return schema._all_defaults()
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")


# Generate accessors for every field in both models. The three
# ``_SKIP_AUTOGEN`` keys have hand-written accessors in
# :mod:`vtsearch.settings.accessors` (``autofind_detectors`` with extra
# semantics - dedupe, add/remove/is_ - and the two directories as ``Path``s);
# the six per-side keys are built by ``_make_per_side_setting`` below.
_SKIP_AUTOGEN = {"autofind_detectors", "saved_datasets_dir", "detectors_dir"}
_PER_SIDE_KEYS = {
    "grid_icon_size_left",
    "grid_icon_size_right",
    "focus_mode_left",
    "focus_mode_right",
    "panel_pct_left",
    "panel_pct_right",
}

for _model in (ServerSettings, UserSettings):
    for _field_name in _model.model_fields:
        if _field_name in _SKIP_AUTOGEN or _field_name in _PER_SIDE_KEYS:
            continue
        _g, _s, _v = _make_scalar_accessors(_model, _field_name)
        globals()[f"get_{_field_name}"] = _g
        globals()[f"set_{_field_name}"] = _s
        globals()[f"validate_{_field_name}"] = _v

del _model, _field_name, _g, _s, _v


