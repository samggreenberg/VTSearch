"""The experiment runners' shared env setup has exactly one home (issue #3411).

``scripts/experiments/_expcommon.py`` exists because its
:func:`neutralise_editable_finder` fails **silently** when it is wrong: a stage
whose ``vtscore`` resolved to the venv's editable install embeds against
whatever code the main checkout is on, with no error and no marker in the
results.  That is #2846, and it used to be copied into three ``common.py``
files plus an inline fourth in ``pile_config.py``, so widening the heuristic
meant landing the same change four times and missing one.

These tests pin both halves of the fix: the behaviour of the shared helpers,
and the invariant that no study re-forks them.  ``scripts/`` has neither type
nor pytest coverage otherwise (``pyrightconfig.json`` excludes it), so without
this the fork can quietly come back.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import pytest

_EXPERIMENTS = Path(__file__).resolve().parents[2] / "scripts" / "experiments"


@pytest.fixture(scope="module")
def expcommon():
    if str(_EXPERIMENTS) not in sys.path:
        sys.path.insert(0, str(_EXPERIMENTS))
    import _expcommon

    return _expcommon


@pytest.fixture
def clean_paths():
    """Restore ``sys.path`` / ``sys.meta_path``; ``setup_env`` edits both."""
    path, meta = list(sys.path), list(sys.meta_path)
    yield
    sys.path[:] = path
    sys.meta_path[:] = meta


class _Editable:
    """Stands in for the venv's ``__editable__.vtsearch`` meta-path finder.

    The real one is a class generated by setuptools into a module named
    ``__editable___vtsearch_..._finder``; the heuristic matches on the module +
    class name, so a stub named the same way is a faithful stand-in.
    """


_Editable.__module__ = "__editable___vtsearch_0_0_0_finder"


class _Innocent:
    """Any other finder — must survive."""


class TestNeutraliseEditableFinder:
    def test_drops_the_editable_finder(self, expcommon, clean_paths):
        keeper = _Innocent()
        sys.meta_path[:] = [keeper, _Editable()]
        expcommon.neutralise_editable_finder()
        assert sys.meta_path == [keeper]

    def test_keeps_every_other_finder(self, expcommon, clean_paths):
        finders = list(sys.meta_path)
        expcommon.neutralise_editable_finder()
        assert sys.meta_path == finders

    def test_is_idempotent(self, expcommon, clean_paths):
        sys.meta_path[:] = [_Editable(), _Innocent()]
        expcommon.neutralise_editable_finder()
        once = list(sys.meta_path)
        expcommon.neutralise_editable_finder()
        assert sys.meta_path == once


class TestSetupEnv:
    def _call(self, expcommon, tmp_path, **kw):
        kw.setdefault("repo", tmp_path / "repo")
        kw.setdefault("datadir", tmp_path / "datadir")
        kw.setdefault("models_dir", tmp_path / "models")
        expcommon.setup_env(**kw)

    def test_exports_and_creates_the_dirs(self, expcommon, tmp_path, monkeypatch, clean_paths):
        for var in ("VTSEARCH_DATA_DIR", "VTSEARCH_MODELS_DIR", "HF_HOME", "TOKENIZERS_PARALLELISM"):
            monkeypatch.delenv(var, raising=False)
        self._call(expcommon, tmp_path, results=tmp_path / "res", hf_home=tmp_path / "hf")
        assert os.environ["VTSEARCH_DATA_DIR"] == str(tmp_path / "datadir")
        assert os.environ["VTSEARCH_MODELS_DIR"] == str(tmp_path / "models")
        assert os.environ["HF_HOME"] == str(tmp_path / "hf")
        assert os.environ["TOKENIZERS_PARALLELISM"] == "false"
        for d in ("datadir", "models", "hf", "res"):
            assert (tmp_path / d).is_dir(), d

    def test_a_preset_var_wins_and_is_the_dir_created(self, expcommon, tmp_path, monkeypatch, clean_paths):
        """A launcher that exports a var keeps control of it — including the mkdir.

        The old per-study copies created ``Path(os.environ[var])`` for exactly
        this reason; a study that made its *default* instead would leave the
        overridden dir missing and the default one an empty decoy.
        """
        monkeypatch.setenv("VTSEARCH_DATA_DIR", str(tmp_path / "override"))
        monkeypatch.delenv("HF_HOME", raising=False)
        self._call(expcommon, tmp_path, hf_home=tmp_path / "hf")
        assert os.environ["VTSEARCH_DATA_DIR"] == str(tmp_path / "override")
        assert (tmp_path / "override").is_dir()
        assert not (tmp_path / "datadir").exists()

    def test_no_hf_home_leaves_hf_alone(self, expcommon, tmp_path, monkeypatch, clean_paths):
        """``inclusion_knob`` never set HF_HOME; ``hf_home=None`` must not start."""
        monkeypatch.delenv("HF_HOME", raising=False)
        self._call(expcommon, tmp_path)
        assert "HF_HOME" not in os.environ

    def test_extra_dirs_are_created(self, expcommon, tmp_path, monkeypatch, clean_paths):
        monkeypatch.delenv("HF_HOME", raising=False)
        self._call(expcommon, tmp_path, extra_dirs=(tmp_path / "cache",))
        assert (tmp_path / "cache").is_dir()

    def test_repo_goes_first_on_sys_path(self, expcommon, tmp_path, clean_paths):
        self._call(expcommon, tmp_path)
        assert sys.path[0] == str(tmp_path / "repo")

    def test_neutralises_by_default(self, expcommon, tmp_path, clean_paths):
        sys.meta_path.append(_Editable())
        self._call(expcommon, tmp_path)
        assert not any(type(f) is _Editable for f in sys.meta_path)

    def test_neutralise_false_leaves_the_finder(self, expcommon, tmp_path, clean_paths):
        """Studies that run from the repo checkout have no wrong worktree to guard."""
        stub = _Editable()
        sys.meta_path.append(stub)
        self._call(expcommon, tmp_path, neutralise=False)
        assert stub in sys.meta_path


class TestNoStudyReforksTheFinder:
    """The invariant the module exists for: one copy, and one only."""

    def test_only_expcommon_touches_sys_meta_path(self):
        offenders = sorted(
            p.relative_to(_EXPERIMENTS).as_posix()
            for p in _EXPERIMENTS.rglob("*.py")
            if "sys.meta_path" in p.read_text(encoding="utf-8")
        )
        assert offenders == ["_expcommon.py"], (
            "these files carry their own copy of the #2846 editable-finder fix; "
            "call `_expcommon.neutralise_editable_finder()` instead: " + ", ".join(offenders)
        )

    @pytest.mark.parametrize(
        "study",
        ["calibration", "max_patch", "mlp_vs_svm", "inclusion_knob", "toponymy_audio", "toponymy_image"],
    )
    def test_study_common_delegates(self, study):
        """Each study's ``common.py`` is constants plus a call, not a copy."""
        src = (_EXPERIMENTS / study / "common.py").read_text(encoding="utf-8")
        assert "_expcommon.setup_env(" in src, f"{study}/common.py does not delegate setup_env"
        assert "def setup_env" in src, f"{study}/common.py must keep its own zero-arg setup_env()"
