"""Background thumbnail warm-up for archive-member datasets.

Most media arrive from a file the loader can read at ingest, so their
``thumbnail_bytes`` are computed once, up front, and every grid / VTSBrowse
tile just streams them.  **Archive-member** media are the exception: the
:mod:`~vtscore.datasets.importers.local_archive_member` importer exists
precisely so a WebDataset-style corpus (tens of thousands of chunks inside a
handful of multi-GB ``shard_*.tar`` files, often 4+ TB unpacked) can be
searched without copying or reading it, so each media leaves import carrying
only ``{archive path, member}`` -- no bytes, no dimensions, and no thumbnail.

Every browse tile therefore took the cold branch of
``GET /api/medias/<id>/thumbnail``: a tar-header scan, a full member read, a
full-resolution decode, a resize, and a re-encode, on the request thread
(~46 ms at 2 MP, ~378 ms at 24 MP).  The route memoises what it generates, so
a second pass over the same region was fast, but the first paint of every
region paid full price and a reload started over.

This module moves that work off the request path: after a load completes, a
background pass walks the dataset, streams each member **once**, generates the
thumbnail through the media type's
:meth:`~vtscore.media.base.MediaType.ensure_thumbnail_bytes` hook, and drops
the member bytes.  Design constraints, all load-bearing:

* **Never blocks.**  The pass runs on its own :class:`JobManager` slot, kicked
  after the dataset is registered and usable.  Browse works throughout;
  partial coverage simply degrades to the per-request behaviour above for
  whatever the pass has not reached yet.
* **Cancellable.**  Each item boundary checks the job's cancel event, so a
  cancel (or a test reset) unwinds promptly rather than after the corpus.
* **Bounded in-flight bytes.**  Members are streamed at
  :data:`_MAX_WORKERS`-way concurrency, but the shards are multi-GB, so a
  worker must reserve its member's size against a byte budget before reading.
  Eight unbounded readers over a video corpus would be an OOM.
* **Representatives first.**  The VTSBrowse canvas only paints one
  *representative* media per hex/square cell, so warming the projection's
  representatives (coarse levels first) makes browse feel fixed long before
  the full pass finishes.

The thumbnails are in-memory artifacts, exactly like every other
``thumbnail_bytes``: they ride along on an explicit save and are otherwise
regenerated by the next warm-up.  Nothing here persists anything, so the
no-persisted-vectors rule is untouched (and a thumbnail is neither an
embedding nor an MLP).
"""

from __future__ import annotations

import logging
import os
import threading
from concurrent.futures import ThreadPoolExecutor
from typing import Any, Callable, Iterable

from vtscore.concurrency.async_jobs import AsyncJob, archive_thumbnail_jobs
from vtscore.concurrency.memory_budget import available_memory_bytes
from vtscore.concurrency.progress import CancelledError
from vtscore.datasets.archive_stream import archive_member_ref

logger = logging.getLogger(__name__)

#: Members streamed concurrently.  Each worker holds at most one member's bytes
#: (plus its decode), and the byte budget below is what actually keeps that
#: bounded -- this is only the parallelism ceiling.
_MAX_WORKERS = 8

#: Share of currently-available memory the warm-up may hold as in-flight member
#: bytes.  Deliberately small: the pass is a background nicety and must never be
#: the reason a foreground load, embed, or sort runs out of room.
_BUDGET_FRACTION = 0.10

#: Hard ceiling and floor on the in-flight byte budget, whatever the host has.
#: The ceiling stops a big-memory box from buffering absurd amounts for no gain
#: (thumbnail throughput is decode-bound well before 1 GiB in flight); the floor
#: keeps the pass alive on a tight host -- a single member always gets through,
#: because :meth:`_ByteBudget.acquire` admits an oversized item alone.
_BUDGET_CEILING = 1024 * 1024 * 1024
_BUDGET_FLOOR = 64 * 1024 * 1024

#: Progress is reported every this many completed items, so a 100k-member
#: corpus doesn't churn the job's counters once per thumbnail.
_PROGRESS_EVERY = 25


def _default_max_workers() -> int:
    """Members to stream concurrently: :data:`_MAX_WORKERS`, CPU-capped.

    The per-item cost is a member read followed by a decode + resize, so the
    decode side is what saturates; there is nothing to gain from more readers
    than the host can decode on.
    """
    return max(2, min(_MAX_WORKERS, os.cpu_count() or 4))


def _default_byte_budget() -> int:
    """In-flight byte ceiling for the warm-up, derived from free memory."""
    budget = int(available_memory_bytes() * _BUDGET_FRACTION)
    return max(_BUDGET_FLOOR, min(_BUDGET_CEILING, budget))


class _ByteBudget:
    """A semaphore counted in *bytes* rather than slots.

    ``ThreadPoolExecutor(max_workers=8)`` bounds how many members are read at
    once but says nothing about how *large* they are, and the corpora this
    importer targets hold multi-GB shards whose individual members can be
    hundreds of MB.  Each worker therefore reserves its member's known size
    (the importer records it as ``file_size`` at import, from the tar header,
    so no read is needed to learn it) before streaming and releases it after
    the thumbnail is extracted.

    An item larger than the whole budget is admitted **alone**, once the rest
    of the in-flight bytes have drained.  Refusing it instead would silently
    skip exactly the biggest members -- the ones whose per-request decode hurts
    most -- and blocking on it forever would stall the pass.
    """

    def __init__(self, limit: int) -> None:
        self._limit = max(1, limit)
        self._in_flight = 0
        self._cond = threading.Condition()

    def acquire(self, size: int, *, should_stop: Callable[[], bool]) -> bool:
        """Reserve *size* bytes.  Returns ``False`` if *should_stop* fired first.

        Waits with a timeout rather than indefinitely so a cancel observed by
        *should_stop* is honoured even while every worker is parked behind a
        full budget.
        """
        size = max(0, size)
        with self._cond:
            while True:
                if should_stop():
                    return False
                # ``self._in_flight == 0`` is the oversized-item escape hatch:
                # nothing else is in flight, so admitting it cannot make the
                # peak any worse than this one item.
                if self._in_flight + size <= self._limit or self._in_flight == 0:
                    self._in_flight += size
                    return True
                self._cond.wait(timeout=0.25)

    def release(self, size: int) -> None:
        with self._cond:
            self._in_flight -= max(0, size)
            if self._in_flight < 0:
                self._in_flight = 0
            self._cond.notify_all()


def _has_browsable_thumbnail(media_type: str) -> bool:
    """Whether *media_type*'s items render a thumbnail worth precomputing."""
    if not media_type:
        return False
    try:
        from vtscore.media import get as get_media_type  # noqa: PLC0415

        return bool(get_media_type(media_type).has_thumbnail)
    except (KeyError, ImportError):
        return False


def pending_archive_thumbnail_ids(medias: dict[int, dict[str, Any]]) -> list[int]:
    """Ids of archive-member media that still need a thumbnail generated.

    A media qualifies when it resolves to an ``{archive, member}`` pair (so its
    bytes stream rather than sit in memory or on disk), its type renders a
    browsable thumbnail, and it has no ``thumbnail_bytes`` yet.  Media that
    already carry one -- warmed by an earlier pass, memoised by a request, or
    loaded from a pickle saved after a completed pass -- are skipped, which is
    what makes the whole pass idempotent and safe to re-kick on every load.
    """
    pending: list[int] = []
    for media_id, media in medias.items():
        if media.get("thumbnail_bytes"):
            continue
        if archive_member_ref(media) is None:
            continue
        if not _has_browsable_thumbnail(media.get("media_type", "")):
            continue
        pending.append(media_id)
    return pending


def _representative_ids(ctx: Any) -> list[int]:
    """Projection representatives, coarsest zoom level first.

    These are the only media the VTSBrowse canvas paints at a given zoom (one
    per cell), so warming them first is what makes browse *look* fixed while
    the long tail is still streaming.  Coarse levels come first because they
    are what the canvas shows on open.  Returns ``[]`` when the dataset has no
    projection yet (it is opt-in at ingest and otherwise built lazily on the
    first Browse visit) -- the caller then falls back to a plain sweep.
    """
    by_level: dict[int, list[int]] = {}
    for pyr in list(getattr(ctx, "_pyramids", {}).values()):
        for (level, _tx, _ty), tile in pyr.tiles.items():
            bucket = by_level.setdefault(level, [])
            for cell in tile.cells:
                bucket.append(int(cell.rep_id))
    ordered: list[int] = []
    for level in sorted(by_level):
        ordered.extend(by_level[level])
    return ordered


def _member_sort_key(media: dict[str, Any]) -> tuple[str, str]:
    """``(archive, member)`` for grouping, or empty strings when unresolvable."""
    ref = archive_member_ref(media)
    return ref if ref is not None else ("", "")


def warm_order(ctx: Any, ids: Iterable[int]) -> list[int]:
    """Order *ids* so browse feels fixed as early as possible.

    Representatives first (coarse zoom levels before fine, per
    :func:`_representative_ids`), then everything else grouped by
    ``(archive, member)``.  The grouping matters for windowed corpora: a
    heavily-windowed audio manifest fans one member out into ~14 clip windows,
    and each window's waveform is sliced from the *same* decoded member.
    Warming a member's windows together means one stream + one decode serves
    all of them through the decode cache in
    :mod:`vtscore.media.audio.media_type`; interleaving members instead would
    evict and re-decode.
    """
    remaining = set(ids)
    ordered: list[int] = []
    seen: set[int] = set()
    for media_id in _representative_ids(ctx):
        if media_id in remaining and media_id not in seen:
            ordered.append(media_id)
            seen.add(media_id)
    tail = sorted(remaining - seen, key=lambda mid: (*_member_sort_key(ctx.medias.get(mid, {})), mid))
    ordered.extend(tail)
    return ordered


def _warm_one(ctx: Any, media_id: int, budget: _ByteBudget, should_stop: Callable[[], bool]) -> bool:
    """Generate one media's thumbnail.  Returns ``True`` if one now exists.

    Every failure mode here is non-fatal by design: a member the manifest
    points at may have been renamed or its shard moved, a codec may be
    unsupported, the dataset may have been unloaded mid-pass.  None of those
    should abort the warm-up for the rest of the corpus -- the affected tile
    just keeps the request-time fallback it had before this pass existed.
    """
    from vtscore.media import get as get_media_type  # noqa: PLC0415

    media = ctx.medias.get(media_id)
    if media is None or media.get("thumbnail_bytes"):
        # Unloaded, or a request beat us to it (the route memoises too).
        return False
    size = media.get("file_size") or 0
    if not budget.acquire(int(size), should_stop=should_stop):
        return False
    try:
        return bool(get_media_type(media["media_type"]).ensure_thumbnail_bytes(media))
    except Exception:
        logger.debug("thumbnail warm-up: media %s could not be warmed", media_id, exc_info=True)
        return False
    finally:
        budget.release(int(size))


def warm_archive_thumbnails(
    ctx: Any,
    *,
    job: AsyncJob | None = None,
    max_workers: int | None = None,
    byte_budget: int | None = None,
) -> int:
    """Generate thumbnails for *ctx*'s archive-member media.  Returns the count.

    Runs to completion unless *job* is cancelled, in which case it returns the
    number warmed so far -- a partial pass is a perfectly good outcome, since
    every un-warmed tile still resolves through the request path.
    """
    from vtscore.state.core import _state_lock  # noqa: PLC0415

    with _state_lock:
        medias_snapshot = dict(ctx.medias)
    pending = pending_archive_thumbnail_ids(medias_snapshot)
    if not pending:
        return 0
    total = len(pending)
    ordered = warm_order(ctx, pending)
    budget = _ByteBudget(byte_budget if byte_budget is not None else _default_byte_budget())

    def should_stop() -> bool:
        # A cancelled job, or a dataset unloaded (or replaced) underneath us.
        from vtscore.state.core import get_context  # noqa: PLC0415

        if job is not None and job.is_cancelled:
            return True
        return get_context(ctx.dataset_id) is not ctx

    warmed = 0
    done = 0
    if job is not None:
        job.update_progress(0, total, "Warming thumbnails…")
    workers = max_workers if max_workers is not None else _default_max_workers()
    with ThreadPoolExecutor(max_workers=workers, thread_name_prefix="thumb-warm") as pool:
        # ``map`` with the default chunking would hand the pool the whole id
        # list up front, so a cancel could not take effect until the queue
        # drained.  Submitting lazily in worker-sized batches keeps the queue
        # short enough that ``should_stop`` is observed within one batch.
        for start in range(0, len(ordered), workers):
            if should_stop():
                break
            batch = ordered[start : start + workers]
            for ok in pool.map(lambda mid: _warm_one(ctx, mid, budget, should_stop), batch):
                done += 1
                warmed += int(ok)
            if job is not None and (done % _PROGRESS_EVERY < workers or done == total):
                job.update_progress(done, total, f"Warming thumbnails… {warmed}/{total}")
    logger.info(
        "thumbnail warm-up: %s/%s archive members warmed for dataset %s%s",
        warmed,
        total,
        ctx.dataset_id,
        " (stopped early)" if warmed < total and should_stop() else "",
    )
    return warmed


def _sweep(job: AsyncJob) -> int:
    """Warm every loaded dataset that has archive-member media awaiting one.

    The sweep walks **all** loaded contexts rather than the one that triggered
    it, which is what makes a single-slot :class:`JobManager` the right home
    for this work.  That manager runs one job at a time and supersedes a parked
    pending one; if each kick only warmed its own dataset, loading three
    archive-member datasets in quick succession would leave two of them
    permanently cold.  Because every kick sweeps everything, a superseded kick
    loses nothing -- whichever job ends up running finishes the work for all of
    them, and an already-warm dataset costs one dictionary scan.
    """
    from vtscore.state.core import get_context, list_loaded_dataset_ids  # noqa: PLC0415

    warmed = 0
    for dataset_id in list_loaded_dataset_ids():
        if job.is_cancelled:
            break
        ctx = get_context(dataset_id)
        if ctx is None:
            continue
        try:
            warmed += warm_archive_thumbnails(ctx, job=job)
        except CancelledError:
            raise
        except Exception:
            # One dataset's failure must not cost the others their warm-up.
            logger.exception("thumbnail warm-up failed for dataset %s", dataset_id)
    job.result = {"warmed": warmed}
    return warmed


def start_archive_thumbnail_warm(ctx: Any) -> str | None:
    """Kick the background warm-up sweep if *ctx* has anything to warm.

    Called at the end of a load (fresh import *and* reload), after the dataset
    is registered and browsable, so the pass never delays the dashboard row
    going green.  Returns the job id, or ``None`` when there is nothing to do
    -- which is the common case, since only archive-member datasets ever leave
    a load without thumbnails.

    Re-kicking on reload is deliberate rather than redundant.  A fresh import
    writes its pickle *before* this pass can run (the save is what makes the
    dataset durable, and blocking it on a whole-corpus stream is exactly the
    cost the importer exists to avoid), so those thumbnails are not in the
    file.  Warming again on load makes the dataset self-heal instead of
    requiring an explicit re-save, and costs nothing when the thumbnails did
    ride along.
    """
    from vtscore.state.core import _state_lock  # noqa: PLC0415

    with _state_lock:
        medias_snapshot = dict(ctx.medias)
    if not pending_archive_thumbnail_ids(medias_snapshot):
        return None
    job = archive_thumbnail_jobs.start(
        ("archive-thumbnail-warm", ctx.dataset_id),
        _sweep,
        dataset_id=ctx.dataset_id,
    )
    return job.job_id
